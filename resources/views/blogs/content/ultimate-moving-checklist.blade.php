<p>Most moving stress doesn't come from the move itself — it comes from the things you remember at the last minute.
    A good checklist, worked through a few weeks ahead of time, turns moving day into something you're ready for
    instead of something that happens to you.</p>

<h2>Four to Six Weeks Before You Move</h2>
<ul>
    <li>Decide what's actually moving with you — this is the easiest time to sort through things you no longer need,
        before they end up packed and moved for nothing</li>
    <li>Get a written quote for your move so you know your budget, whether you're moving locally or between cities
    </li>
    <li>Start collecting packing materials if you're packing yourself, or book a mover who provides them</li>
    <li>Note down your new address and confirm access — lift availability, parking for a truck, and any building
        permissions you might need at either end</li>
</ul>

<h2>Two Weeks Before You Move</h2>
<ul>
    <li>Begin packing rooms you use least first — storage areas, spare rooms, and out-of-season items</li>
    <li>Start using up food from the fridge and freezer so there's less to deal with on moving day</li>
    <li>Arrange for utilities — electricity, water, internet — to be transferred or disconnected at your old address
        and connected at the new one</li>
    <li>Update your address with your bank, workplace and anywhere else that sends you post regularly</li>
</ul>

<h2>The Week Before You Move</h2>
<ul>
    <li>Finish packing everything except what you'll need in the last day or two</li>
    <li>Pack a separate "first day" bag with essentials — chargers, medicines, a change of clothes, basic toiletries
        — so you're not digging through boxes on your first night</li>
    <li>Confirm your moving date and time with your movers, and reconfirm access at both addresses</li>
    <li>Take photos of any furniture you've disassembled, so it's easier to put back together</li>
</ul>

<h2>On Moving Day</h2>
<ul>
    <li>Do a final walkthrough of every room, including cupboards and drawers, before the crew leaves</li>
    <li>Keep valuables, documents and your first-day bag with you rather than on the truck</li>
    <li>Check off items against your inventory as they're loaded, if you have one</li>
    <li>Note the meter readings at your old home before you hand over the keys</li>
</ul>

<h2>After You Arrive</h2>
<p>Unpack the essentials first — kitchen basics, bedding and bathroom items — and let the rest wait until you've had
    a night's rest. Check your inventory once more as things are unloaded, so you know straightaway if anything is
    missing rather than finding out weeks later.</p>

