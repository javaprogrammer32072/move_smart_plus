<p>Fragile items are usually what people worry about most before a move — not the sofa or the wardrobe, but the
    dinner set that's been in the family for years, or the TV you just bought. The good news is that most breakages
    happen for the same handful of reasons, and all of them are avoidable with the right packing approach.</p>

<h2>Why Fragile Items Break in Transit</h2>
<p>Items rarely break because a box was dropped. More often, it's because there was empty space inside the box that
    let things shift and knock against each other, or because a heavy item was packed on top of a lighter, more
    delicate one. Getting the packing order and cushioning right solves most of the problem before the box is even
    sealed.</p>

<h2>What You'll Need Before You Start</h2>
<ul>
    <li>Sturdy, double-walled cartons in a few sizes — small boxes for heavy items like books or crockery, larger
        ones for lighter, bulkier items</li>
    <li>Packing paper or newspaper for wrapping individual pieces</li>
    <li>Bubble wrap for anything with a screen, a curved surface, or sharp edges</li>
    <li>Tape and a marker to seal boxes and label them clearly</li>
</ul>

<h2>Packing Glassware, Crockery and Kitchen Items</h2>
<p>Wrap each plate, bowl or glass individually rather than stacking them loosely with paper between layers — loose
    stacking is one of the most common causes of chipped crockery. Plates should be packed on their edge, like
    records in a crate, not flat — a stack of flat plates concentrates weight on the bottom piece and cracks it.
    Glasses and cups should be stuffed with paper on the inside before wrapping, since an empty glass is more likely
    to crack under pressure.</p>
<p>Line the bottom of the box with a layer of crumpled paper before you start, and fill any gaps at the end with more
    paper so nothing can move once the box is closed.</p>

<h2>Packing Electronics, Mirrors and Frames</h2>
<p>Where you still have the original box for a TV or appliance, use it — it's built for exactly this. If you don't,
    wrap the item in bubble wrap with the bubbles facing inward, and pack it upright in a box sized close to its
    actual dimensions, so it can't tip over during loading.</p>
<p>Mirrors, photo frames and anything with glass should be wrapped flat, with cardboard on both sides for rigidity,
    and marked clearly so the crew handling your move knows to keep it upright and on the outside of the stack, not
    underneath heavier boxes.</p>

<h2>Common Mistakes to Avoid</h2>
<ul>
    <li>Packing heavy books or crockery into oversized boxes — the box becomes too heavy to carry safely and more
        likely to be dropped</li>
    <li>Leaving empty space at the top of a box instead of filling it with paper</li>
    <li>Forgetting to label boxes as "Fragile" and marking which side should face up</li>
    <li>Stacking fragile boxes underneath heavier ones in the vehicle</li>
</ul>

